            "      spc_aft_pt: 0.0",
            "      ln_spc_pct: 100000",
            "",
            "table_defaults:",
            "  min_row_height_in: 0.4",
            "  cell_padding_emu: 45720",
            "  header_row_height_in: 0.5",
            "  width_step_emu: 45720",
            "  default_width_in: 1.5",
            "  row_header_width_in: 1.0",
            "  moon_width_in: 0.7",
            "  bullets_width_in: 4.0",
            "  superheader_pt_boost: 2",
