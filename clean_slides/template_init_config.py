            "  arc_adjustments:",
            '    "100": null',
            '    "75": ["16200000", "0"]',
            '    "50": ["16200000", "10800000"]',
            '    "25": ["16200000", "5400000"]',
            '    "0": ["16200000", "16200000"]',
            "  fills:",
            "    critical: 100",
